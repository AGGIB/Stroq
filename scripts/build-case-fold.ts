// Derives packages/core/src/rules/prefilter/case-fold-table.ts from the regex engine of the Node
// that runs this script. Run it with `pnpm build:case-fold` after a change to the derivation or
// when a new Node brings a newer Unicode; packages/core/test/rules/prefilter/case-fold.test.ts
// fails if the committed table is not what the engine says.
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { collapseGroups, engineClasses, type FoldFlags } from './lib/case-fold-derive.js';

const root = resolve(import.meta.dirname, '..');
const outFile = join(root, 'packages/core/src/rules/prefilter/case-fold-table.ts');

const hex = (code: number): string => `0x${code.toString(16)}`;

function render(name: string, flags: FoldFlags): string {
  const groups = collapseGroups(engineClasses(flags));
  const rows = groups.map((group) => `  [${group.map(hex).join(', ')}],`);
  return `export const ${name}: readonly (readonly number[])[] = [\n${rows.join('\n')}\n];\n`;
}

const text = `// Generated by scripts/build-case-fold.ts: do not edit by hand.
//
// Each group lists characters that the engine treats as the same under the \`i\` flag but that stay
// different after \`toLowerCase\`: all but the first turn into the first. See case-fold.ts, and
// case-fold.test.ts, which checks this table against the engine.

${render('COLLAPSE_I', 'i')}
${render('COLLAPSE_IU', 'iu')}`;

writeFileSync(outFile, text);
process.stdout.write(`wrote ${outFile}\n`);
